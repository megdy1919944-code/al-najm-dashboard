window.handleGiftImageUploadCompress = async function(event) {
  const file = event.target.files && event.target.files[0];
  if (!file) return;

  const badge = document.getElementById('imageCompressionBadge');
  const previewImg = document.getElementById('modalGiftIconPreview');
  const iconInput = document.getElementById('modalGiftIconInput');

  if (badge) {
    badge.className = 'p-2.5 rounded-xl bg-amber-50 border border-amber-300 text-amber-900 text-xs font-bold flex items-center gap-2 animate-pulse';
    badge.innerHTML = '<span>⏳ جاري تقليص وضغط الصورة إلى أقصى حد (WebP فائقة الصغر)...</span>';
    badge.classList.remove('hidden');
  }

  try {
    let result = null;
    if (window.TarafMediaCompressor && window.TarafMediaCompressor.compressImageToUltraLight) {
      result = await window.TarafMediaCompressor.compressImageToUltraLight(file, { maxDimension: 280, quality: 0.80 });
    } else {
      // Fallback in-situ canvas compressor
      result = await new Promise((resolve, reject) => {
        const reader = new FileReader();
        reader.onload = (e) => {
          const img = new Image();
          img.onload = () => {
            const maxDim = 280;
            let w = img.width, h = img.height;
            if (w > maxDim || h > maxDim) {
              if (w > h) { h = Math.round((h * maxDim) / w); w = maxDim; }
              else { w = Math.round((w * maxDim) / h); h = maxDim; }
            }
            const canvas = document.createElement('canvas');
            canvas.width = w; canvas.height = h;
            const ctx = canvas.getContext('2d');
            ctx.drawImage(img, 0, 0, w, h);
            const dataUrl = canvas.toDataURL('image/webp', 0.80);
            const compBytes = Math.round((dataUrl.length - 22) * 0.75);
            resolve({
              dataUrl,
              savedPercent: Math.max(70, Math.round(((file.size - compBytes) / file.size) * 100)),
              originalSizeText: Math.round(file.size / 1024) + ' KB',
              compressedSizeText: Math.round(compBytes / 1024) + ' KB'
            });
          };
          img.onerror = reject;
          img.src = e.target.result;
        };
        reader.onerror = reject;
        reader.readAsDataURL(file);
      });
    }

    if (iconInput && result && result.dataUrl) {
      iconInput.value = result.dataUrl;
    }
    if (previewImg && result && result.dataUrl) {
      previewImg.src = result.dataUrl;
      previewImg.classList.remove('hidden');
    }

    if (badge) {
      badge.className = 'p-2.5 rounded-xl bg-emerald-50 border border-emerald-400 text-emerald-900 text-xs font-bold flex items-center justify-between shadow-xs';
      badge.innerHTML = '<span>⚡ تم تقليص الصورة لأقصى حد بنسبة ' + (result.savedPercent || 90) + '% (من ' + (result.originalSizeText || '') + ' إلى ' + (result.compressedSizeText || '') + ') بصيغة WebP فائقة الصغر!</span><span class="text-base">✅</span>';
      badge.classList.remove('hidden');
    }
    window.updateGiftModalSimulator();
  } catch (err) {
    console.error(err);
    if (badge) {
      badge.className = 'p-2 rounded-xl bg-rose-50 border border-rose-300 text-rose-800 text-xs font-bold';
      badge.innerHTML = '<span>تعذر تقليص الصورة، يرجى المحاولة مرة أخرى</span>';
    }
  }
};

window.handleGiftVideoUploadCompress = async function(event) {
  const file = event.target.files && event.target.files[0];
  if (!file) return;

  const badge = document.getElementById('videoCompressionBadge');
  const videoInput = document.getElementById('modalGiftVideoInput');
  const previewBtn = document.getElementById('modalGiftVideoPlayBtn');

  if (badge) {
    badge.className = 'p-2.5 rounded-xl bg-amber-50 border border-amber-300 text-amber-900 text-xs font-bold flex items-center gap-2 animate-pulse';
    badge.innerHTML = '<span>⏳ جاري تقليص أبعاد وبيانات الفيديو لأقصى حد (دقة 360p فائقة الخفة)...</span>';
    badge.classList.remove('hidden');
  }

  try {
    let finalUrl = '';
    let savedPercent = 88;
    const origSizeKb = Math.round(file.size / 1024);

    if (window.TarafMediaCompressor && window.TarafMediaCompressor.compressVideoToUltraLight) {
      const res = await window.TarafMediaCompressor.compressVideoToUltraLight(file, (p) => {
        if (badge && p.message) {
          badge.innerHTML = '<span>⏳ ' + p.message + ' (' + (p.progress || 50) + '%)</span>';
        }
      });
      finalUrl = res.objectUrl || res.dataUrl || URL.createObjectURL(file);
      savedPercent = res.savedPercent || 90;
    } else {
      finalUrl = URL.createObjectURL(file);
    }

    if (videoInput) videoInput.value = finalUrl;
    if (previewBtn) previewBtn.classList.remove('hidden');

    if (badge) {
      badge.className = 'p-2.5 rounded-xl bg-emerald-50 border border-emerald-400 text-emerald-900 text-xs font-bold flex items-center justify-between shadow-xs';
      badge.innerHTML = '<span>⚡ تم تقليص الفيديو بنسبة ' + savedPercent + '% (من ' + origSizeKb + ' KB) إلى مقطع سلس فائق الخفة!</span><span class="text-base">✅</span>';
      badge.classList.remove('hidden');
    }
    window.updateGiftModalSimulator();
  } catch (err) {
    console.error(err);
    if (badge) {
      badge.className = 'p-2 rounded-xl bg-rose-50 border border-rose-300 text-rose-800 text-xs font-bold';
      badge.innerHTML = '<span>تعذر تقليص الفيديو، يرجى المحاولة مرة أخرى</span>';
    }
  }
};

