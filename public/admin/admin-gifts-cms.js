// Get Gifts (Supports both super_legend_gifts_database_v2 and super_legend_gifts_cms_v3)
window.getRoomGiftsCatalog = function() {
  try {
    const rawApp = localStorage.getItem('super_legend_gifts_database_v2');
    if (rawApp) {
      const parsed = JSON.parse(rawApp);
      if (Array.isArray(parsed) && parsed.length > 0) return parsed;
    }
    const rawCms = localStorage.getItem(window.ROOM_GIFTS_STORAGE_KEY);
    if (rawCms) {
      const parsed = JSON.parse(rawCms);
      if (Array.isArray(parsed) && parsed.length > 0) return parsed;
    }
  } catch (e) {}
  return [...window.OFFICIAL_ROOM_GIFTS_DATA];
};

window.saveRoomGiftsCatalog = function(giftsList) {
  try {
    // 1. Save to both keys for 100% interoperability with user app and dashboard
    localStorage.setItem('super_legend_gifts_database_v2', JSON.stringify(giftsList));
    localStorage.setItem(window.ROOM_GIFTS_STORAGE_KEY, JSON.stringify(giftsList));

    // 2. Broadcast across channels
    window.dispatchEvent(new CustomEvent("taraf_gifts_updated", { detail: giftsList }));
    
    if (typeof window !== 'undefined' && 'BroadcastChannel' in window) {
      try {
        const ch = new BroadcastChannel('super_legend_gifts_cms_sync_channel');
        ch.postMessage({ type: 'GIFTS_UPDATED', payload: giftsList, timestamp: Date.now() });
        setTimeout(() => ch.close(), 100);
      } catch (err) {}
      try {
        const tarafCh = new BroadcastChannel('taraf_rooms_channel');
        tarafCh.postMessage({ type: 'GIFTS_UPDATED', gifts: giftsList, timestamp: Date.now() });
        setTimeout(() => tarafCh.close(), 100);
      } catch (err) {}
    }

    if (window.top && window.top !== window) {
      window.top.postMessage({ type: "GIFTS_UPDATED", gifts: giftsList }, "*");
    }
  } catch (e) {}
};

// Web Audio API Procedural Sound Synthesizer (Exactly matching App giftCmsService)
window.playAppGiftSound = function(preset, volume) {
  if (volume === undefined) volume = 0.8;
  try {
    const AudioCtx = window.AudioContext || window.webkitAudioContext;
    if (!AudioCtx) return;
    const ctx = new AudioCtx();
    const masterGain = ctx.createGain();
    masterGain.gain.setValueAtTime(volume * 0.4, ctx.currentTime);
    masterGain.connect(ctx.destination);
    const now = ctx.currentTime;

    switch (preset) {
      case "lion_roar": {
        const osc = ctx.createOscillator();
        const gain = ctx.createGain();
        osc.type = "sawtooth";
        osc.frequency.setValueAtTime(140, now);
        osc.frequency.exponentialRampToValueAtTime(45, now + 1.2);
        gain.gain.setValueAtTime(0.6, now);
        gain.gain.exponentialRampToValueAtTime(0.01, now + 1.2);
        osc.connect(gain);
        gain.connect(masterGain);
        osc.start(now);
        osc.stop(now + 1.2);
        break;
      }
      case "jackpot_bells": {
        [523.25, 659.25, 783.99, 1046.5, 1318.5, 1567.98].forEach((freq, idx) => {
          const osc = ctx.createOscillator();
          const gain = ctx.createGain();
          const t = now + idx * 0.1;
          osc.type = "sine";
          osc.frequency.setValueAtTime(freq, t);
          gain.gain.setValueAtTime(0.5, t);
          gain.gain.exponentialRampToValueAtTime(0.001, t + 0.5);
          osc.connect(gain);
          gain.connect(masterGain);
          osc.start(t);
          osc.stop(t + 0.5);
        });
        break;
      }
      case "magic_sparkle": {
        [440, 554.37, 659.25, 880, 1108.73, 1318.51, 1760].forEach((freq, idx) => {
          const osc = ctx.createOscillator();
          const gain = ctx.createGain();
          const t = now + idx * 0.08;
          osc.type = "triangle";
          osc.frequency.setValueAtTime(freq, t);
          gain.gain.setValueAtTime(0.4, t);
          gain.gain.exponentialRampToValueAtTime(0.001, t + 0.6);
          osc.connect(gain);
          gain.connect(masterGain);
          osc.start(t);
          osc.stop(t + 0.6);
        });
        break;
      }
      case "supercar": {
        const osc = ctx.createOscillator();
        const gain = ctx.createGain();
        osc.type = "sawtooth";
        osc.frequency.setValueAtTime(80, now);
        osc.frequency.exponentialRampToValueAtTime(520, now + 1.4);
        gain.gain.setValueAtTime(0.4, now);
        gain.gain.exponentialRampToValueAtTime(0.01, now + 1.4);
        osc.connect(gain);
        gain.connect(masterGain);
        osc.start(now);
        osc.stop(now + 1.4);
        break;
      }
      case "laser": {
        const osc = ctx.createOscillator();
        const gain = ctx.createGain();
        osc.type = "sawtooth";
        osc.frequency.setValueAtTime(1800, now);
        osc.frequency.exponentialRampToValueAtTime(120, now + 0.4);
        gain.gain.setValueAtTime(0.5, now);
        gain.gain.exponentialRampToValueAtTime(0.001, now + 0.4);
        osc.connect(gain);
        gain.connect(masterGain);
        osc.start(now);
        osc.stop(now + 0.4);
        break;
      }
      case "kiss": {
        const osc = ctx.createOscillator();
        const gain = ctx.createGain();
        osc.type = "sine";
        osc.frequency.setValueAtTime(600, now);
        osc.frequency.exponentialRampToValueAtTime(1200, now + 0.15);
        gain.gain.setValueAtTime(0.6, now);
        gain.gain.exponentialRampToValueAtTime(0.001, now + 0.35);
        osc.connect(gain);
        gain.connect(masterGain);
        osc.start(now);
        osc.stop(now + 0.35);
        break;
      }
      case "boom": {
        const osc = ctx.createOscillator();
        const gain = ctx.createGain();
        osc.type = "sine";
        osc.frequency.setValueAtTime(180, now);
        osc.frequency.exponentialRampToValueAtTime(30, now + 0.8);
        gain.gain.setValueAtTime(0.8, now);
        gain.gain.exponentialRampToValueAtTime(0.001, now + 0.8);
        osc.connect(gain);
        gain.connect(masterGain);
        osc.start(now);
        osc.stop(now + 0.8);
        break;
      }
      case "applause": {
        [400, 600, 800, 1000].forEach((f, i) => {
          const osc = ctx.createOscillator();
          const gain = ctx.createGain();
          osc.type = "triangle";
          osc.frequency.setValueAtTime(f, now + i * 0.05);
          gain.gain.setValueAtTime(0.3, now + i * 0.05);
          gain.gain.exponentialRampToValueAtTime(0.001, now + 0.8);
          osc.connect(gain);
          gain.connect(masterGain);
          osc.start(now + i * 0.05);
          osc.stop(now + 0.8);
        });
        break;
      }
      case "fanfare":
      default: {
        const notes = [523.25, 659.25, 783.99, 1046.5];
        notes.forEach((freq, idx) => {
          const osc = ctx.createOscillator();
          const gain = ctx.createGain();
          const t = now + idx * 0.12;
          osc.type = "sine";
          osc.frequency.setValueAtTime(freq, t);
          gain.gain.setValueAtTime(0.5, t);
          gain.gain.exponentialRampToValueAtTime(0.001, t + 0.8);
          osc.connect(gain);
          gain.connect(masterGain);
          osc.start(t);
          osc.stop(t + 0.8);
        });
        break;
      }
    }
  } catch (err) {
    console.warn("Audio synthesis error:", err);
  }
};

window.playGiftAudioEffect = function(gift) {
  if (!gift) return;
  if (gift.soundUrl) {
    try {
      const audio = new Audio(gift.soundUrl);
      audio.volume = 0.8;
      audio.play().catch(() => {
        window.playAppGiftSound(gift.soundPreset || "fanfare");
      });
      return;
    } catch (e) {}
  }
  window.playAppGiftSound(gift.soundPreset || "fanfare");
};

