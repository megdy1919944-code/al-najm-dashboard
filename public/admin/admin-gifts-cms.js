window.saveGiftModalData = function(giftId) {
  const nameInput = document.getElementById('modalGiftName');
  const badgeInput = document.getElementById('modalGiftBadge');
  const catInput = document.getElementById('modalGiftCategory');
  const priceInput = document.getElementById('modalGiftPrice');
  const iconInput = document.getElementById('modalGiftIconInput');
  const videoInput = document.getElementById('modalGiftVideoInput');
  const soundPresetInput = document.getElementById('modalGiftSoundPreset');
  const hasSoundInput = document.getElementById('modalGiftHasSound');
  const broadcastInput = document.getElementById('modalGiftBroadcast');
  const refundInput = document.getElementById('modalGiftIsRefundable');
  const renderLayerInput = document.getElementById('modalGiftRenderLayer');
  const placementInput = document.getElementById('modalGiftPlacement');
  const scaleInput = document.getElementById('modalGiftScaleInput');

  const name = nameInput ? nameInput.value.trim() : '';
  const price = priceInput ? parseInt(priceInput.value, 10) : 100;
  const category = catInput ? catInput.value : 'الفعالية';
  const badge = badgeInput ? badgeInput.value.trim() : '';
  const icon = iconInput ? iconInput.value.trim() : '🎁';
  const videoUrl = videoInput ? videoInput.value.trim() : '';
  const soundPreset = soundPresetInput ? soundPresetInput.value : 'fanfare';
  const hasSound = hasSoundInput ? hasSoundInput.checked : true;
  const hasGlobalBroadcast = broadcastInput ? broadcastInput.checked : false;
  const isRefundable = refundInput ? refundInput.checked : false;
  const renderLayer = renderLayerInput ? renderLayerInput.value : 'behind_mics';
  const placement = placementInput ? placementInput.value : 'bottom';
  const scale = scaleInput ? parseFloat(scaleInput.value) : 1.0;
  const displayPosition = placement === 'top' ? 'above' : (placement === 'bottom' ? 'below' : 'center');

  if (!name) {
    alert('يرجى كتابة اسم الهدية!');
    return;
  }
  if (!price || price <= 0) {
    alert('يرجى كتابة سعر صحيح بالكوينز!');
    return;
  }

  const allGifts = window.getRoomGiftsCatalog();

  if (giftId) {
    const idx = allGifts.findIndex(g => g.id === giftId);
    if (idx !== -1) {
      allGifts[idx] = {
        ...allGifts[idx],
        name,
        price,
        category,
        badge,
        icon,
        videoUrl,
        animationUrl: videoUrl,
        soundPreset,
        hasSound,
        hasGlobalBroadcast,
        isRefundable,
        isRefund: isRefundable,
        isLucky: isRefundable,
        renderLayer,
        placement,
        displayPosition,
        scale
      };
    }
  } else {
    const newId = 'gift_' + Date.now();
    allGifts.unshift({
      id: newId,
      name,
      price,
      category,
      badge,
      icon,
      videoUrl,
      animationUrl: videoUrl,
      soundPreset,
      hasSound,
      hasGlobalBroadcast,
      isRefundable,
      isRefund: isRefundable,
      isLucky: isRefundable,
      renderLayer,
      placement,
      displayPosition,
      scale,
      durationSeconds: 4.0
    });
  }

  window.saveRoomGiftsCatalog(allGifts);

  const modal = document.getElementById('giftCMSModal');
  if (modal) modal.remove();

  const container = document.getElementById('dynamicViewContainer');
  if (container) window.renderGiftsCatalogView(container);

  window.showAdminNotification ? window.showAdminNotification('تم حفظ الهدية وتحديث صندوق الروم بنجاح! 🎁', 'success') : alert('تم حفظ الهدية وتحديث صندوق الروم بنجاح! 🎁');
};

