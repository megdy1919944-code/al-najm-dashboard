// Interactive Simulator preview inside the modal
window.updateGiftModalSimulator = function() {
  const simBehindBox = document.getElementById('simBehindLayer');
  const simAboveBox = document.getElementById('simAboveLayer');
  const layerInput = document.getElementById('modalGiftRenderLayer');
  const placementInput = document.getElementById('modalGiftPlacement');
  const scaleInput = document.getElementById('modalGiftScaleInput');
  const iconInput = document.getElementById('modalGiftIconInput');

  if (!simBehindBox || !simAboveBox) return;

  const layer = layerInput ? layerInput.value : 'behind_mics';
  const placement = placementInput ? placementInput.value : 'bottom';
  const scale = scaleInput ? parseFloat(scaleInput.value) : 1.0;
  const iconVal = iconInput && iconInput.value ? iconInput.value.trim() : '🦁';

  // Render gift asset in simulator
  let assetHtml = '';
  if (iconVal.startsWith('http') || iconVal.startsWith('data:image')) {
    assetHtml = '<img src="' + iconVal + '" class="w-14 h-14 object-contain filter drop-shadow-lg" style="transform: scale(' + scale + ');" />';
  } else {
    assetHtml = '<span class="text-4xl filter drop-shadow-lg inline-block" style="transform: scale(' + scale + ');">' + iconVal + '</span>';
  }

  // Positioning classes
  let posClass = 'items-center justify-center';
  if (placement === 'bottom') posClass = 'items-end justify-center pb-2';
  else if (placement === 'top') posClass = 'items-start justify-center pt-2';
  else if (placement === 'mics') posClass = 'items-center justify-center -translate-y-2';
  else if (placement === 'fullscreen') posClass = 'items-center justify-center inset-0 w-full h-full';

  if (layer === 'behind_mics') {
    simBehindBox.className = 'absolute inset-0 z-1 pointer-events-none flex ' + posClass;
    simBehindBox.innerHTML = assetHtml;
    simAboveBox.innerHTML = '';
    simAboveBox.className = 'hidden';
  } else {
    simAboveBox.className = 'absolute inset-0 z-30 pointer-events-none flex ' + posClass;
    simAboveBox.innerHTML = assetHtml;
    simBehindBox.innerHTML = '';
    simBehindBox.className = 'hidden';
  }
};

